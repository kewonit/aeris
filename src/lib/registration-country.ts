const MARKS_BY_LENGTH = [...NATIONALITY_MARKS].sort(
  (left, right) => right[0].length - left[0].length,
);

// "B-" is shared by mainland China, Taiwan, Hong Kong, and Macao, and "N"
// only marks a US registration when a digit follows it.
const PATTERN_MARKS: readonly [pattern: RegExp, code: string, name: string][] = [
  [/^N[1-9][0-9A-Z]{0,4}$/, "US", "United States"],
  [/^B-[HKL][A-Z]{2}$/, "HK", "Hong Kong"],
  [/^B-M[A-Z]{2}$/, "MO", "Macao"],
  [/^B-\d{5}$/, "TW", "Taiwan"],
  [/^B-[0-9A-Z]{4}$/, "CN", "China"],
];

export function registrationCountry(
  registration: unknown,
): RegistrationCountry | null {
  if (typeof registration !== "string") return null;
  const normalized = registration.trim().toUpperCase();
  if (!normalized) return null;

  for (const [pattern, code, name] of PATTERN_MARKS) {
    if (pattern.test(normalized)) return { code, name };
  }
  for (const [mark, code, name] of MARKS_BY_LENGTH) {
    if (normalized.startsWith(mark) && normalized.length > mark.length) {
      return { code, name };
    }
  }
  return null;
}

export function countryFlagEmoji(code: string | null): string | null {
  if (!code || !/^[A-Z]{2}$/.test(code)) return null;
  return String.fromCodePoint(
    ...[...code].map((character) => character.charCodeAt(0) + 127397),
  );
}
